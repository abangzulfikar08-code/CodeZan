// Uji UI di browser tiruan (jsdom): npm install lalu npm run test:ui
const {JSDOM, VirtualConsole} = require("jsdom"), fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..", "..");
let html = fs.readFileSync(path.join(root, "index.html"), "utf8");
html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, s) => `<script>${fs.readFileSync(path.join(root, s), "utf8")}</script>`);
const errs = [], vc = new VirtualConsole();
vc.on("jsdomError", e => errs.push(e.message)); vc.on("error", e => errs.push(String(e)));
const dom = new JSDOM(html, {url: "http://localhost/", runScripts: "dangerously", pretendToBeVisual: true, virtualConsole: vc});
const w = dom.window; w.scrollTo = () => {}; const d = w.document, app = () => d.querySelector("#app").textContent;
const click = sel => { const el = d.querySelector(sel); if (!el) throw new Error("tidak ada: " + sel); el.click(); };
const set = (sel, v) => { const el = d.querySelector(sel); if (!el) throw new Error("tidak ada: " + sel); el.value = v; el.dispatchEvent(new w.Event("input", {bubbles: true})); };
const cek = (nama, ok) => { console.log((ok ? "OK   " : "GAGAL") + " " + nama); if (!ok) errs.push("gagal: " + nama); };
cek("Beranda tampil", app().includes("Beranda") && app().includes("Isi saldo utama"));
set("#is", "1500000"); click('[data-act="isi"]');
cek("Isi saldo menambah saldo utama", app().includes("Rp1.500.000"));
click('[data-act="go"][data-v="fin"]');
cek("Halaman keuangan: anggaran per kategori + kalkulator + asisten", ["Anggaran per kategori", "Kalkulator", "Asisten otomatis", "Rencana uang bulanan"].every(x => app().includes(x)));
set("#bk0", "50000"); click('[data-act="saveAnggaran"]');
set("#ta", "80000"); d.querySelector("#tc").value = "Makan"; click('[data-act="add"]');
cek("Transaksi tersimpan dan anggaran Makan terlampaui", app().includes("Anggaran Makan terlampaui"));
cek("Pola pengeluaran tampil", app().includes("Pola pengeluaran") && app().includes("Kebutuhan"));
set("#kt", "1000000"); set("#kn", "250000");
cek("Kalkulator live: 750.000", d.querySelector("#ko").textContent.includes("Rp750.000"));
set("#ru", "2000000"); set("#rn", "300000"); click('[data-act="saveR"]');
cek("Rencana disimpan (jatah 1.700.000)", app().includes("Rp1.700.000"));
click('[data-act="go"][data-v="wo"]');
cek("Halaman workout lengkap", ["Jadwal Workout Harian", "Kebiasaan hari ini", "Keperluan hari ini", "Asisten otomatis", "Data tubuh"].every(x => app().includes(x)));
click('[data-act="hb"][data-id="protein"]'); click('[data-act="hb"][data-id="air"]'); click('[data-act="hb"][data-id="tidur"]');
cek("3 kebiasaan = streak 1 hari", app().includes("Streak: 1 hari") && app().includes("3/5 selesai"));
set("#pw", "61"); click('[data-act="saveP"]'); set("#nw", "61.5"); click('[data-act="addWt"]');
cek("Berat tercatat", app().includes("61.5 kg"));
const tersimpan = JSON.parse(w.localStorage.getItem("mkg-v1"));
cek("State tersimpan (bk, hb, tx)", tersimpan.bk.Makan === 50000 && Object.keys(tersimpan.hb).length === 1 && tersimpan.tx.length === 2);
click('[data-act="go"][data-v="home"]');
cek("Beranda menampilkan asisten dan boleh dikeluarkan", app().includes("Asisten otomatis") && app().includes("Boleh dikeluarkan sekarang"));
set("#pn", "1234"); click('[data-act="setPin"]');
cek("PIN tersimpan", JSON.parse(w.localStorage.getItem("mkg-v1")).pin === "1234");
console.log(errs.length ? "\nERROR:\n" + errs.join("\n") : "\nSemua lolos tanpa error konsol.");
process.exit(errs.length ? 1 : 0);
